#!/usr/bin/env python3
"""Aggregates results/bench/*.record.json into summary.md and summary.json.

Reads, never recomputes a score: chain_correct and evidence_read come from the
runner. Reports min / median / max everywhere there is a spread, never a mean
on its own, and the integrity of the run set first (a missing or invalid run
must be visible before any figure).

Usage: bench_report.py [results-dir]
"""
import glob
import json
import os
import statistics as st
import sys

D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results", "bench")
ENGINES = ["kagent", "holmes-native", "holmes-mcp", "doc-engine"]
SCENARIOS = ["missing-secret-key", "proxy-timeout", "bad-config-rollout"]
# Alert firing times of the 2026-10-23 bench (from out/bench.log), to date each run.
FIRED = {"missing-secret-key": "2026-10-23T08:27:29", "proxy-timeout": "2026-10-23T09:53:14",
         "bad-config-rollout": "2026-10-23T12:47:29"}
LATE_MIN = 35  # events TTL is 30 min: later runs see the namespace without its events

recs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(D, "*.record.json")))]
main = [r for r in recs if not r["control"]]
ctrl = [r for r in recs if r["control"]]


def rng(xs, fmt="{:.0f}"):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "n/a"
    return " / ".join(fmt.format(v) for v in (min(xs), st.median(xs), max(xs)))


def age_min(r):
    import datetime as dt
    t = dt.datetime.fromisoformat(r["recorded_at"][:19])
    a = dt.datetime.fromisoformat(FIRED[r["scenario"]])
    return (t - a).total_seconds() / 60


def u(r, k):
    return (r.get("usage") or {}).get(k)


out, js = [], {"integrity": {}, "cells": {}, "engines": {}, "controls": [], "age": {}}

# 1. integrity first
bad = []
for e in ENGINES:
    for s in SCENARIOS:
        cell = [r for r in main if r["engine"] == e and r["scenario"] == s]
        if len(cell) != 5:
            bad.append(f"{e}/{s}: {len(cell)} runs, expected 5")
inv = [r["run"] for r in main if not r["valid"]]
repl = [(r["run"], [a["cause"] for a in r["attempts"]]) for r in main if r["replayed"]]
instr = [r["run"] for r in main if r.get("instrumentation_error")]
nousage = [r["run"] for r in main if not r.get("usage")]
js["integrity"] = {"records": len(recs), "main": len(main), "controls": len(ctrl), "cells_not_5": bad,
                   "invalid_runs": inv, "replayed": repl, "instrumentation_errors": instr, "runs_without_usage": nousage}
out += ["# Bench summary (generated by scripts/bench_report.py)", "",
        "## Integrity", "",
        f"- records: {len(recs)} ({len(main)} measured runs + {len(ctrl)} controls)",
        f"- cells (engine x scenario) without exactly 5 runs: {bad or 'none'}",
        f"- invalid runs (not counted as correct): {inv or 'none'}",
        f"- replayed after an infrastructure failure: {repl or 'none'}",
        f"- instrumentation errors: {instr or 'none'}; runs without usage: {nousage or 'none'}", ""]

# 2. per engine x scenario
out += ["## Per engine and scenario (min / median / max)", "",
        "| Engine | Scenario | Chain correct | Evidence read | Latency s | Model calls | Input tokens | Cost $ | Tool calls |",
        "|---|---|---|---|---|---|---|---|---|"]
for e in ENGINES:
    for s in SCENARIOS:
        c = [r for r in main if r["engine"] == e and r["scenario"] == s]
        v = [r for r in c if r["valid"]]
        cc = sum(1 for r in v if r.get("chain_correct"))
        ev = sum(1 for r in v if r.get("evidence_read"))
        js["cells"][f"{e}/{s}"] = {"n": len(c), "valid": len(v), "chain_correct": cc, "evidence_read": ev}
        out.append(f"| {e} | {s} | {cc}/{len(c)} | {ev}/{len(c)} | {rng([r['latency_seconds'] for r in c])} | "
                   f"{rng([u(r, 'model_calls') for r in c])} | {rng([u(r, 'input_tokens') for r in c], '{:,.0f}')} | "
                   f"{rng([u(r, 'cost_usd') for r in c], '{:.3f}')} | {rng([r['tool_call_count'] for r in c])} |")
out.append("")

# 3. per engine, all scenarios
out += ["## Per engine, all 15 runs", "",
        "| Engine | Chain correct | Evidence read | Latency s | Model calls | Input tokens | Cost $ |", "|---|---|---|---|---|---|---|"]
for e in ENGINES:
    c = [r for r in main if r["engine"] == e]
    cc = sum(1 for r in c if r.get("chain_correct")); ev = sum(1 for r in c if r.get("evidence_read"))
    js["engines"][e] = {"n": len(c), "chain_correct": cc, "evidence_read": ev,
                        "latency_median": st.median([r["latency_seconds"] for r in c]),
                        "cost_median": st.median([u(r, "cost_usd") for r in c if u(r, "cost_usd") is not None])}
    out.append(f"| {e} | {cc}/{len(c)} | {ev}/{len(c)} | {rng([r['latency_seconds'] for r in c])} | "
               f"{rng([u(r, 'model_calls') for r in c])} | {rng([u(r, 'input_tokens') for r in c], '{:,.0f}')} | "
               f"{rng([u(r, 'cost_usd') for r in c], '{:.3f}')} |")
out.append("")

# 4. controls
out += ["## Controls: question only, no instructions (proxy-timeout, 2 runs per HolmesGPT variant)", "",
        "| Run | Engine | Chain correct (spec 04) | Evidence read | Mentions memory | Answer chars |", "|---|---|---|---|---|---|"]
for r in sorted(ctrl, key=lambda r: r["run"]):
    js["controls"].append({"run": r["run"], "engine": r["engine"], "chain_correct": r.get("chain_correct"),
                           "evidence_read": r.get("evidence_read")})
    out.append(f"| {r['run']} | {r['engine']} | {r.get('chain_correct')} | {r.get('evidence_read')} | {r['memory_mentioned']} | {r['answer_chars']} |")
cc = sum(1 for r in ctrl if r.get("chain_correct")); ev = sum(1 for r in ctrl if r.get("evidence_read"))
out += ["", f"Controls: chain correct {cc}/{len(ctrl)}, evidence read {ev}/{len(ctrl)}. "
        "Instructed HolmesGPT runs on the same incident: "
        + ", ".join(f"{e} chain {sum(1 for r in main if r['engine']==e and r['scenario']=='proxy-timeout' and r.get('chain_correct'))}/5 "
                    f"evidence {sum(1 for r in main if r['engine']==e and r['scenario']=='proxy-timeout' and r.get('evidence_read'))}/5"
                    for e in ("holmes-native", "holmes-mcp")) + ".", ""]

# 5. age confound
out += [f"## Run age (events TTL is 30 min: runs recorded more than {LATE_MIN} min after the alert saw the namespace without its events)", "",
        "| Scenario | Runs recorded late | Of 20 | Input tokens, early runs (median) | Input tokens, late runs (median) |", "|---|---|---|---|---|"]
for s in SCENARIOS:
    c = [r for r in main if r["scenario"] == s]
    late = [r for r in c if age_min(r) > LATE_MIN]; early = [r for r in c if age_min(r) <= LATE_MIN]
    js["age"][s] = {"late_runs": [r["run"] for r in late], "early_runs": [r["run"] for r in early]}
    em = st.median([u(r, "input_tokens") for r in early if u(r, "input_tokens")]) if early else None
    lm = st.median([u(r, "input_tokens") for r in late if u(r, "input_tokens")]) if late else None
    out.append(f"| {s} | {len(late)} | {len(c)} | {em:,.0f} | {lm if lm is None else format(lm, ',.0f')} |" if em is not None
               else f"| {s} | {len(late)} | {len(c)} | n/a | {lm} |")
out.append("")

open(os.path.join(D, "summary.md"), "w").write("\n".join(out))
json.dump(js, open(os.path.join(D, "summary.json"), "w"), indent=2)
print("\n".join(out))
