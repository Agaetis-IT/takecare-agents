#!/usr/bin/env bash
# Generates the gateway's MCP backends, one route per (identity, server), and
# the per-route tool allow-list, into manifests/gateway/mcp-routes.yaml.
# The route is the caller's identity at the gateway (ADR 0008):
#   /mcp/<identity>/<server>
# Usage: scripts/routes.sh [--apply]
source "$(dirname "$0")/lib.sh"

OUT="${SPIKE_DIR}/manifests/gateway/mcp-routes.yaml"

# server -> "host port" (bash 3.2 on macOS: no associative arrays)
target() {
  case "$1" in
    kubernetes) echo "kubernetes-mcp-server.mcp.svc.cluster.local 8080" ;;
    prometheus) echo "mcp-prometheus.mcp.svc.cluster.local 8080" ;;
    incidents) echo "mcp-incidents.mcp.svc.cluster.local 3000" ;;
    runbooks) echo "mcp-runbooks.mcp.svc.cluster.local 3000" ;;
    deployments) echo "mcp-deployments.mcp.svc.cluster.local 3000" ;;
    vendor) echo "mcp-vendor.mcp.svc.cluster.local 3000" ;;
    support) echo "mcp-support.mcp.svc.cluster.local 3000" ;;
  esac
}
SERVERS=(kubernetes prometheus incidents runbooks deployments vendor support)

# The Doc's `read` tools, per server. Milestone 1 gives `read` tools only at
# every level (ADR 0008), so doc-trial and doc-service get the same list; the
# Holmes baseline gets it too, so that both engines see the same tools.
# Left out on purpose:
#   kubernetes: nodes_* (no node rights), namespaces_list (cluster scope)
#   prometheus: get_alertmanager_alerts, get_alertmanagers (caller-supplied
#               alertmanager_url), get_config, get_flags, get_runtime_info,
#               get_build_info, get_tsdb_stats, check_ready, query_exemplars,
#               get_targets_metadata (no diagnostic value)
#   support:    support_create_ticket (`act`)
read_tools() {
  case "$1" in
    kubernetes) echo "events_list pods_list pods_list_in_namespace pods_get pods_log pods_top resources_list resources_get" ;;
    prometheus) echo "execute_query execute_range_query list_label_names list_label_values find_series get_metric_metadata get_alerts get_rules get_targets" ;;
    incidents) echo "incidents_search incidents_get incidents_recent" ;;
    runbooks) echo "runbooks_search runbooks_get runbooks_recent" ;;
    deployments) echo "deployments_search deployments_get deployments_recent" ;;
    vendor) echo "vendor_search vendor_get vendor_recent" ;;
    support) echo "support_search support_get support_recent" ;;
  esac
}
IDENTITIES=(doc-trial doc-service holmes)

cel_list() { local t out=""; for t in $1; do out+="\"${t}\", "; done; printf '[%s]' "${out%, }"; }

{
  echo "# GENERATED by scripts/routes.sh — do not edit by hand."
  for s in "${SERVERS[@]}"; do
    read -r host port <<<"$(target "$s")"
    cat <<EOF
---
apiVersion: agentgateway.dev/v1alpha1
kind: AgentgatewayBackend
metadata:
  name: mcp-${s}
  namespace: ${AGW_NS}
spec:
  mcp:
    # One target per backend: no tool-name prefix (prefixMode Conditional).
    targets:
      - name: ${s}
        static: { host: ${host}, port: ${port}, path: /mcp, protocol: StreamableHTTP }
EOF
  done
  for id in "${IDENTITIES[@]}"; do
    for s in "${SERVERS[@]}"; do
      cat <<EOF
---
apiVersion: gateway.networking.k8s.io/v1
kind: HTTPRoute
metadata:
  name: mcp-${id}-${s}
  namespace: ${AGW_NS}
  labels: { takecare.spike/identity: ${id}, takecare.spike/server: ${s} }
spec:
  parentRefs: [{ name: agentgateway-proxy, sectionName: http }]
  rules:
    - matches: [{ path: { type: PathPrefix, value: /mcp/${id}/${s} } }]
      backendRefs: [{ group: agentgateway.dev, kind: AgentgatewayBackend, name: mcp-${s} }]
---
# Require, with a single expression: several expressions under Allow are OR'd,
# and policies from different attachment levels merge.
apiVersion: agentgateway.dev/v1alpha1
kind: AgentgatewayPolicy
metadata:
  name: mcp-${id}-${s}-tools
  namespace: ${AGW_NS}
  labels: { takecare.spike/identity: ${id}, takecare.spike/server: ${s} }
spec:
  targetRefs: [{ group: gateway.networking.k8s.io, kind: HTTPRoute, name: mcp-${id}-${s} }]
  backend:
    mcp:
      authorization:
        action: Require
        policy:
          matchExpressions:
            - 'mcp.tool.name in $(cel_list "$(read_tools "$s")")'
EOF
    done
  done
} > "$OUT"
log "wrote ${OUT}"

if [[ "${1:-}" == --apply ]]; then
  kubectl apply -f "$OUT" >/dev/null
  log "applied $(grep -c '^kind:' "$OUT") objects"
fi
